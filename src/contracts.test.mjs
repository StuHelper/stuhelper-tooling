import { checkContracts, checkGeneratedHeader } from './contracts.mjs';
import createFrontendCheckPreset, { accessibleTemplateSelectors, cjkLiteralSelector } from '../presets/frontend-eslint.mjs';

const sha256 = text => crypto.createHash('sha256').update(text).digest('hex');

test('generated Go and TypeScript headers reject hand-written files lacking generator markers', () => {
  assert.deepEqual(checkGeneratedHeader('sdk/catalog.gen.go', '// Code generated by oapi-codegen DO NOT EDIT.\npackage sdk\n'), []);
  assert.deepEqual(checkGeneratedHeader('src/api/catalog.gen.ts', '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\nexport interface paths {}\n'), []);
  assert.equal(checkGeneratedHeader('sdk/catalog.gen.go', 'package sdk\n').length, 1);
  assert.equal(checkGeneratedHeader('src/api/catalog.gen.ts', 'export interface paths {}\n').length, 1);
});

test('contracts checker verifies source manifests, SHA-256 digests and OpenAPI version sync', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'stuhelper-contracts-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, 'contracts'), { recursive: true });
  fs.mkdirSync(path.join(root, 'src/api'), { recursive: true });

  const spec = JSON.stringify({ openapi: '3.1.0', info: { title: 'Catalog', version: '0.8.0' }, paths: {} }, null, 2);
  const sdk = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\nexport interface paths {}\n';
  fs.writeFileSync(path.join(root, 'contracts/catalog.openapi.json'), spec);
  fs.writeFileSync(path.join(root, 'src/api/catalog.gen.ts'), sdk);
  fs.writeFileSync(
    path.join(root, 'contracts/catalog.source.json'),
    JSON.stringify({
      repository: 'StuHelper/stuhelper-catalog',
      revision: 'a'.repeat(40),
      version: '0.8.0',
      files: {
        'contracts/catalog.openapi.json': 'contracts/catalog.openapi.json',
        'sdk/catalog.gen.ts': 'src/api/catalog.gen.ts',
      },
      sha256: {
        'contracts/catalog.openapi.json': sha256(spec),
        'src/api/catalog.gen.ts': sha256(sdk),
      },
    }),
  );
  assert.deepEqual(checkContracts(root), []);

  // Tampering with generated SDK without updating manifest fails SHA-256 verification.
  fs.writeFileSync(path.join(root, 'src/api/catalog.gen.ts'), `${sdk}// manual edit\n`);
  assert.match(checkContracts(root).join('\n'), /src\/api\/catalog\.gen\.ts SHA-256 mismatch/);

  // Version drift between OpenAPI info.version and source.json fails.
  fs.writeFileSync(path.join(root, 'src/api/catalog.gen.ts'), sdk);
  const bumpedSpec = JSON.stringify({ openapi: '3.1.0', info: { title: 'Catalog', version: '0.9.0' }, paths: {} }, null, 2);
  fs.writeFileSync(path.join(root, 'contracts/catalog.openapi.json'), bumpedSpec);
  fs.writeFileSync(
    path.join(root, 'contracts/catalog.source.json'),
    JSON.stringify({
      repository: 'StuHelper/stuhelper-catalog',
      revision: 'a'.repeat(40),
      version: '0.8.0',
      sha256: { 'contracts/catalog.openapi.json': sha256(bumpedSpec), 'src/api/catalog.gen.ts': sha256(sdk) },
    }),
  );
  assert.match(checkContracts(root).join('\n'), /info\.version "0\.9\.0" differs from snapshot version "0\.8\.0"/);
});

test('contracts checker rejects isolated manual edits to *.gen.* without contract or generator updates', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'stuhelper-gen-edit-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
  git('init', '-q', '-b', 'develop');
  git('config', 'user.name', 'Fixture');
  git('config', 'user.email', 'fixture@example.invalid');
  git('config', 'commit.gpgSign', 'false');

  fs.mkdirSync(path.join(root, 'contracts'), { recursive: true });
  fs.mkdirSync(path.join(root, 'sdk'), { recursive: true });
  fs.writeFileSync(path.join(root, 'contracts/reviews.openapi.json'), '{"openapi":"3.1.0","info":{"title":"Reviews","version":"1.0.0"}}\n');
  fs.writeFileSync(path.join(root, 'sdk/reviews.gen.go'), '// Code generated by oapi-codegen DO NOT EDIT.\npackage sdk\n');
  git('add', '.');
  git('commit', '-qm', 'initial contract and sdk');

  // Hand-editing sdk/reviews.gen.go alone must fail.
  fs.writeFileSync(path.join(root, 'sdk/reviews.gen.go'), '// Code generated by oapi-codegen DO NOT EDIT.\npackage sdk\nvar HandEdited = true\n');
  const cli = fileURLToPath(new URL('../bin/stuhelper-check.mjs', import.meta.url));
  const bad = spawnSync(process.execPath, [cli, 'contracts'], { cwd: root, encoding: 'utf8' });
  assert.equal(bad.status, 1);
  assert.match(bad.stderr, /generated file modified without corresponding contract or generator update/);

  // Updating the OpenAPI contract alongside the regenerated SDK passes.
  fs.writeFileSync(path.join(root, 'contracts/reviews.openapi.json'), '{"openapi":"3.1.0","info":{"title":"Reviews","version":"1.1.0"}}\n');
  const good = spawnSync(process.execPath, [cli, 'contracts'], { cwd: root, encoding: 'utf8' });
  assert.equal(good.status, 0, good.stderr);
});

test('frontend lefthook and ESLint accessibility/i18n presets provide valid configurations', () => {
  const lefthookFrontend = YAML.parse(fs.readFileSync(new URL('../presets/lefthook-frontend.yml', import.meta.url), 'utf8'));
  assert.equal(lefthookFrontend['pre-commit'].jobs[0].run, 'pnpm exec stuhelper-check staged --eslint');

  const preset = createFrontendCheckPreset({ vueFiles: ['apps/web-antd/src/**/*.vue'] });
  assert.equal(preset.length, 2);
  const rawRule = preset[0].rules['@intlify/vue-i18n/no-raw-text'];
  assert.equal(rawRule[0], 'error');
  assert.ok(rawRule[1].attributes['/.*/'].includes('aria-label'));
  assert.ok(rawRule[1].attributes['/.*/'].includes('alt'));
  assert.equal(preset[0].rules['jsonc/no-dupe-keys'], 'error');
  assert.deepEqual(preset[1].files, ['apps/web-antd/src/**/*.vue']);
  assert.deepEqual(preset[1].rules['vue/no-restricted-syntax'].slice(1), accessibleTemplateSelectors);
  assert.equal(preset[1].rules['no-restricted-syntax'][1], cjkLiteralSelector);
});

test('scalar contract digests require a companion snapshot', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'stuhelper-companion-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, 'contracts'));
  for (const key of ['sha256', 'contract_sha256']) {
    fs.writeFileSync(path.join(root, 'contracts/api.source.json'), JSON.stringify({revision: 'a'.repeat(40), [key]: sha256('spec')}));
    assert.match(checkContracts(root).join('\n'), /missing.*contract/i);
  }
});

test('Vue lint visits template elements and script literals', async () => {
  const { ESLint } = await import('eslint');
  const { default: vue } = await import('eslint-plugin-vue');
  const { default: parser } = await import('vue-eslint-parser');
  const [, rules] = createFrontendCheckPreset();
  const lint = new ESLint({ overrideConfigFile: true, overrideConfig: [
    { ...rules, plugins: { vue }, languageOptions: { parser } }
  ] });
  const run = async source => (await lint.lintText(source, { filePath: 'src/Example.vue' }))[0].messages.map(m => m.ruleId);
  const bad = await run('<template><div><img src="photo.png"><button/><span @click="go"/></div></template><script>const title="课程";</script>');
  assert.equal(bad.filter(id => id === 'vue/no-restricted-syntax').length, 3, JSON.stringify(bad));
  assert.ok(bad.includes('no-restricted-syntax'));
  assert.deepEqual(await run('<template><div><img alt=""><button aria-label="Save"/><span/></div></template>'), []);
});
